// Package manifests vendors components' Kubernetes manifests into
// deploy/vendor and checks that what is vendored is what versions.yaml
// pins.
//
// Vendoring reads each path a component lists under `manifests` from its
// source repository at its pinned version. Each manifest becomes its own
// kustomize base: deploy/ax.yaml lands in deploy/vendor/<component>/
// deploy/ax/, next to a generated kustomization.yaml that lists it, so a
// profile can take, patch or leave out each manifest separately (two
// manifests that both declare the same Namespace can't share one base).
// A component's files (versions.yaml's `files`, not Kubernetes objects)
// are copied as they are to the same path, with no kustomization.
// deploy/vendor/<component>/VENDOR.yaml records the source, the version
// and every vendored file's SHA-256.
//
// Fetching needs git and the network; verifying needs neither. Verify
// catches a pin moved without a re-vendor and a file edited without its
// lock, offline. It cannot catch an edit made together with a matching
// lock entry, or an upstream tag that moved; for those, CI re-vendors
// online and fails on any difference (dev/tools/verify-vendor-fresh).
package manifests

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/go-steer/shipmind/internal/bom"
)

// Dir is where vendored manifests live, relative to the directory that
// holds versions.yaml.
const Dir = "deploy/vendor"

// LockFile is the name of the per-component lock in Dir/<component>/.
const LockFile = "VENDOR.yaml"

// KustomizationFile is the generated kustomize base in Dir/<component>/.
const KustomizationFile = "kustomization.yaml"

const generatedHeader = "# Generated by `shipmind vendor`. Do not edit; change versions.yaml and re-vendor.\n"

// BaseDir is the directory, relative to Dir/<component>, that holds
// manifest m and its kustomization: "deploy/ax.yaml" -> "deploy/ax".
func BaseDir(m string) string {
	return strings.TrimSuffix(m, path.Ext(m))
}

// vendoredPath is where manifest m is stored, relative to
// Dir/<component>.
func vendoredPath(m string) string {
	return path.Join(BaseDir(m), path.Base(m))
}

// kustomization renders the base for manifest m.
func kustomization(m string) []byte {
	return []byte(generatedHeader +
		"apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - " + path.Base(m) + "\n")
}

// Lock records what was vendored for one component.
type Lock struct {
	Source  string `yaml:"source"`
	Version string `yaml:"version"`
	// Commit is the commit Version resolved to when vendored, so a tag
	// that later moves shows up as a diff on the next re-vendor.
	Commit string `yaml:"commit"`
	// Files maps each vendored path to "sha256:<hex>" of its content.
	Files map[string]string `yaml:"files"`
}

// A Fetcher reads files from a repository at a version.
type Fetcher interface {
	// Fetch returns the files and the commit version resolved to.
	Fetch(ctx context.Context, source, version string, paths []string) (files map[string][]byte, commit string, err error)
}

var fullSHA = regexp.MustCompile(`^[0-9a-f]{40}$`)

// Git fetches with the git command: a depth-1 fetch of exactly the
// pinned commit or tag into a scratch repository.
type Git struct {
	// URL maps a source ("github.com/org/repo") to a clone URL. Nil
	// means "https://<source>.git".
	URL func(source string) string
}

// Fetch implements Fetcher.
func (g Git) Fetch(ctx context.Context, source, version string, paths []string) (map[string][]byte, string, error) {
	url := "https://" + source + ".git"
	if g.URL != nil {
		url = g.URL(source)
	}
	ref := "refs/tags/" + version
	if fullSHA.MatchString(version) {
		ref = version
	}

	dir, err := os.MkdirTemp("", "shipmind-vendor-")
	if err != nil {
		return nil, "", err
	}
	defer func() { _ = os.RemoveAll(dir) }()

	git := func(args ...string) ([]byte, error) {
		// The URL and ref come from versions.yaml, which `shipmind check`
		// has validated; exec passes them as arguments, never to a shell.
		cmd := exec.CommandContext(ctx, "git", append([]string{"-C", dir}, args...)...) //nolint:gosec // see above
		cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0")
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		out, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("git %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
		}
		return out, nil
	}
	if _, err := git("init", "-q"); err != nil {
		return nil, "", err
	}
	if _, err := git("fetch", "-q", "--depth=1", "--no-tags", url, ref); err != nil {
		return nil, "", fmt.Errorf("%s@%s: %w", source, version, err)
	}
	out, err := git("rev-parse", "FETCH_HEAD^{commit}")
	if err != nil {
		return nil, "", fmt.Errorf("%s@%s: %w", source, version, err)
	}
	commit := strings.TrimSpace(string(out))
	files := make(map[string][]byte, len(paths))
	for _, p := range paths {
		b, err := git("show", "FETCH_HEAD:"+p)
		if err != nil {
			return nil, "", fmt.Errorf("%s@%s: %s: %w", source, version, p, err)
		}
		files[p] = b
	}
	return files, commit, nil
}

// Layout reports manifests whose vendored files would collide: two
// manifests in one place, a file where another needs a directory, or a
// file on the lock. Paths are compared case-insensitively, because a
// checkout on a case-insensitive filesystem would merge them.
func Layout(c bom.Component) error {
	files := map[string]string{strings.ToLower(LockFile): "the lock"}
	dirs := map[string]string{}
	var errs []error
	add := func(p, what string) {
		key := strings.ToLower(p)
		if other, ok := files[key]; ok {
			errs = append(errs, fmt.Errorf("%s: %s would be vendored to %s, which %s already uses", c.Name, what, p, other))
		}
		if other, ok := dirs[key]; ok {
			errs = append(errs, fmt.Errorf("%s: %s would be vendored to %s, a directory %s needs", c.Name, what, p, other))
		}
		files[key] = what
		for d := path.Dir(key); d != "."; d = path.Dir(d) {
			if other, ok := files[d]; ok {
				errs = append(errs, fmt.Errorf("%s: %s needs directory %s, which is %s's file", c.Name, what, d, other))
			}
			dirs[d] = what
		}
	}
	for _, m := range c.Manifests {
		add(vendoredPath(m), fmt.Sprintf("manifest %q", m))
		add(path.Join(BaseDir(m), KustomizationFile), fmt.Sprintf("manifest %q", m))
	}
	for _, f := range c.Files {
		add(f, fmt.Sprintf("file %q", f))
	}
	return errors.Join(errs...)
}

// Vendor fetches c's manifests and replaces root/Dir/<c.Name> with
// them (and its files) and a fresh lock. The new tree is written beside
// the old one and renamed into place, so a failure leaves the old tree
// as it was. A component with nothing to vendor is an error.
func Vendor(ctx context.Context, f Fetcher, root string, c bom.Component) error {
	if len(c.Vendored()) == 0 {
		return fmt.Errorf("%s: no manifests or files to vendor", c.Name)
	}
	if err := Layout(c); err != nil {
		return err
	}
	files, commit, err := f.Fetch(ctx, c.Source, c.Version, c.Vendored())
	if err != nil {
		return err
	}
	lock := Lock{Source: c.Source, Version: c.Version, Commit: commit, Files: map[string]string{}}
	for _, p := range c.Vendored() {
		b, ok := files[p]
		if !ok {
			return fmt.Errorf("%s: fetcher returned no %s", c.Name, p)
		}
		lock.Files[p] = digest(b)
	}

	dir := filepath.Join(root, Dir, c.Name)
	if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp(filepath.Dir(dir), "."+c.Name+".vendor-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := writeTree(tmp, c, files, lock); err != nil {
		return err
	}
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	return os.Rename(tmp, dir)
}

func writeTree(dir string, c bom.Component, files map[string][]byte, lock Lock) error {
	if err := os.Chmod(dir, 0o755); err != nil { //nolint:gosec // vendored manifests are meant to be readable
		return err
	}
	put := func(rel string, b []byte) error {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		return os.WriteFile(p, b, 0o644) //nolint:gosec // manifests are meant to be readable
	}
	for _, m := range c.Manifests {
		if err := put(vendoredPath(m), files[m]); err != nil {
			return err
		}
		if err := put(path.Join(BaseDir(m), KustomizationFile), kustomization(m)); err != nil {
			return err
		}
	}
	for _, f := range c.Files {
		if err := put(f, files[f]); err != nil {
			return err
		}
	}
	b, err := yaml.Marshal(lock)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, LockFile), append([]byte(generatedHeader), b...), 0o644) //nolint:gosec // as above
}

// Verify checks, offline, that root/Dir/<c.Name> holds exactly c's
// manifests and files at c's version, unedited. A component with
// neither must have no vendor directory.
func Verify(root string, c bom.Component) error {
	dir := filepath.Join(root, Dir, c.Name)
	if len(c.Vendored()) == 0 {
		if _, err := os.Stat(dir); err == nil {
			return fmt.Errorf("%s: %s exists but versions.yaml lists no manifests or files", c.Name, filepath.ToSlash(filepath.Join(Dir, c.Name)))
		}
		return nil
	}

	b, err := os.ReadFile(filepath.Join(dir, LockFile))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("%s: not vendored (run `shipmind vendor %s`)", c.Name, c.Name)
		}
		return err
	}
	var lock Lock
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&lock); err != nil {
		return fmt.Errorf("%s: %s: %w", c.Name, LockFile, err)
	}

	if err := Layout(c); err != nil {
		return err
	}
	var errs []error
	fail := func(format string, args ...any) {
		errs = append(errs, fmt.Errorf("%s: %s", c.Name, fmt.Sprintf(format, args...)))
	}
	if !fullSHA.MatchString(lock.Commit) {
		fail("%s has no resolved commit (run `shipmind vendor %s`)", LockFile, c.Name)
	}
	if lock.Source != c.Source || lock.Version != c.Version {
		fail("vendored from %s@%s, but versions.yaml pins %s@%s (run `shipmind vendor %s`)",
			lock.Source, lock.Version, c.Source, c.Version, c.Name)
	}
	if want, got := slices.Sorted(slices.Values(c.Vendored())), slices.Sorted(maps.Keys(lock.Files)); !slices.Equal(want, got) {
		fail("vendored files %v, but versions.yaml lists %v (run `shipmind vendor %s`)", got, want, c.Name)
	}

	// Every file on disk must be a manifest, its generated kustomization,
	// a listed file or the lock; every one of those must be on disk,
	// unedited.
	expected := map[string]func([]byte) error{}
	for _, m := range c.Manifests {
		want, ok := lock.Files[m]
		if !ok {
			continue // already reported as a file-list mismatch
		}
		expected[vendoredPath(m)] = func(b []byte) error {
			if digest(b) != want {
				return fmt.Errorf("%s was edited after vendoring (re-vendor, or patch it in a profile instead)", vendoredPath(m))
			}
			return nil
		}
		k := path.Join(BaseDir(m), KustomizationFile)
		expected[k] = func(b []byte) error {
			if !bytes.Equal(b, kustomization(m)) {
				return fmt.Errorf("%s was edited after vendoring (re-vendor instead)", k)
			}
			return nil
		}
	}
	for _, f := range c.Files {
		want, ok := lock.Files[f]
		if !ok {
			continue // already reported as a file-list mismatch
		}
		expected[f] = func(b []byte) error {
			if digest(b) != want {
				return fmt.Errorf("%s was edited after vendoring (re-vendor instead)", f)
			}
			return nil
		}
	}
	// Walk through an os.Root so a symlink in the vendor tree can't make
	// the check read (and bless) a file outside it.
	vendorRoot, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer func() { _ = vendorRoot.Close() }()
	fsys := vendorRoot.FS()
	seen := map[string]bool{}
	err = fs.WalkDir(fsys, ".", func(rel string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		if rel == LockFile {
			return nil
		}
		check, ok := expected[rel]
		if !ok {
			fail("%s is not a vendored manifest, its kustomization or a vendored file", rel)
			return nil
		}
		seen[rel] = true
		b, err := fs.ReadFile(fsys, rel)
		if err != nil {
			return err
		}
		if err := check(b); err != nil {
			fail("%v", err)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, p := range slices.Sorted(maps.Keys(expected)) {
		if !seen[p] {
			fail("%s is missing (run `shipmind vendor %s`)", p, c.Name)
		}
	}
	return errors.Join(errs...)
}

func digest(b []byte) string {
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// Strays reports directories under root/Dir that belong to no component
// in f, such as a component that was removed without its manifests.
func Strays(root string, f *bom.File) error {
	entries, err := os.ReadDir(filepath.Join(root, Dir))
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	var errs []error
	for _, e := range entries {
		if _, ok := f.Component(e.Name()); !ok {
			errs = append(errs, fmt.Errorf("%s/%s: no component %q in versions.yaml", Dir, e.Name(), e.Name()))
		}
	}
	return errors.Join(errs...)
}
