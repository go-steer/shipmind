// slackManifest is switchboard's Slack app manifest, a file versions.yaml
// vendors for the switchboard component.
const slackManifest = "deploy/slack/app-manifest.yaml"

// runSlackApp prints an environment's Slack app manifest: switchboard's,
// at the version the environment's shipmind pin vendors, under the names
// in its shipmind.yaml.
func runSlackApp(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("shipmind slack-app", flag.ContinueOnError)
	fs.SetOutput(stderr)
	root := fs.String("root", ".", "the shipmind checkout, at the commit the environment pins")
	anyRef := fs.Bool("any-ref", false, "allow a checkout at another commit or with uncommitted changes")
	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}
	if fs.NArg() != 1 {
		fmt.Fprintln(stderr, "shipmind slack-app: want one environment directory")
		return 2
	}
	out, err := slackApp(fs.Arg(0), *root, *anyRef)
	if err != nil {
		fmt.Fprintf(stderr, "shipmind slack-app: %v\n", err)
		return 1
	}
	_, _ = stdout.Write(out)
	return 0
}

func slackApp(dir, root string, anyRef bool) ([]byte, error) {
	e, err := env.Load(dir)
	if err != nil {
		return nil, err
	}
	if e.Slack == nil {
		return nil, fmt.Errorf("%s: no slack block naming the environment's Slack app", filepath.Join(dir, env.FileName))
	}
	// The same pin check status and up make: the manifest must come from
	// the switchboard version this environment deploys.
	res, err := overlay.Render(dir, root, overlay.Options{AnyRef: anyRef})
	if err != nil {
		return nil, err
	}
	f, err := bom.Load(filepath.Join(root, "versions.yaml"))
	if err != nil {
		return nil, err
	}
	c, ok := f.Component("switchboard")
	if !ok || !slices.Contains(c.Files, slackManifest) {
		return nil, fmt.Errorf("versions.yaml vendors no switchboard %s", slackManifest)
	}
	if err := manifests.Verify(root, c); err != nil {
		return nil, err
	}
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path.Join(manifests.Dir, c.Name, slackManifest))))
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf(`Slack app manifest for %s (context %s), generated by
shipmind slack-app from switchboard %s's %s
as shipmind %s vendors it. Don't edit; rerun after moving the pin.

New app: https://api.slack.com/apps -> Create New App -> From an app
manifest. Existing app: paste into its App Manifest page, and reinstall
it if scopes changed. switchboard's docs/slack-setup.md covers tokens.`,
		e.Slack.App, e.Context, c.Version, slackManifest, res.Ref[:12])
	return slackapp.Render(b, *e.Slack, header)
}
